def _contract() -> dict[str, Any]:
    return load_contract()


def _question_details(rq_id: str) -> tuple[str, str]:
    """Return a v8 question even while the root contract is being replaced."""

    contract = _contract()
    details = contract.get("research_questions", {}).get(rq_id, {})
    text = str(details.get("text", ""))
    scope = str(details.get("scope", ""))
    is_old_one_day_contract = (
        "Open[t+2]" in text
        or "open-to-open direction" in text
        or "thirteen TSLA strategies" in scope
    )
    if not text or is_old_one_day_contract:
        text = _V8_FALLBACK_QUESTIONS[rq_id]
    if not scope or is_old_one_day_contract:
        scope = _V8_FALLBACK_SCOPES[rq_id]
    return text, scope


def _show_question(rq_id: str) -> None:
    text, scope = _question_details(rq_id)
    st.info(text)
    st.caption(f"Evidence scope: {scope}")






def _format_table(
    frame: pd.DataFrame,
    *,
    percent_columns: tuple[str, ...] = (),
    pp_columns: tuple[str, ...] = (),
    p_columns: tuple[str, ...] = (),
    digits: int = 2,
) -> pd.DataFrame:
    display = frame.copy()
    for column in percent_columns:
        if column in display:
            display[column] = display[column].map(
                lambda value: percentage(value, digits=digits)
            )
    for column in pp_columns:
        if column in display:
            display[column] = display[column].map(
                lambda value: percentage_points(value, digits=digits)
            )
    for column in p_columns:
        if column in display:
            display[column] = display[column].map(
                lambda value: "—" if pd.isna(value) else f"{float(value):.3f}"
            )
    return display


def _show_figure(figure: plt.Figure) -> None:
    st.pyplot(figure, width="stretch")
    plt.close(figure)


def _period_label(period: str) -> str:
    if period == "Development OOF":
        return "Development out-of-fold"
    return "Retrospective later-period audit"


