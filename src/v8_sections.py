def _filter_rq4(
    model_results: pd.DataFrame,
    headline: pd.DataFrame,
    *,
    period: str,
    asset: str,
    models: list[str],
) -> tuple[pd.DataFrame, pd.DataFrame]:
    model_frame = model_results.loc[model_results["Period"].eq(period)].copy()
    headline_frame = headline.loc[headline["Period"].eq(period)].copy()
    if asset != "All assets":
        model_frame = model_frame.loc[model_frame["Asset"].eq(asset)]
        headline_frame = headline_frame.loc[headline_frame["Asset"].eq(asset)]
    model_frame = model_frame.loc[model_frame["Strategy"].isin(models)]
    headline_frame = headline_frame.loc[
        headline_frame["Strategy"].isin(models)
        | headline_frame["Strategy"].isin(BASELINES)
    ]
    return model_frame, headline_frame


