"""Build the frozen v7 news/model provenance manifest with file hashes."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
from pathlib import Path

import pandas as pd


FNSPID_ID = "benstaf/FNSPID-filtered-nasdaq-100"
FNSPID_REVISION = "c5cebb37e76d64d27d79ca72ede8f93b84e1a8aa"
FINBERT_ID = "ProsusAI/finbert"
FINBERT_REVISION = "1b7521e9fc2e2a12e93de7e3e19373b0505d353f"


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def record(
    *,
    category: str,
    identifier: str,
    revision: str,
    path: Path,
    source_url: str,
    license_name: str,
    included: bool,
    role: str,
) -> dict[str, object]:
    return {
        "Category": category,
        "Identifier": identifier,
        "Revision": revision,
        "Filename": path.name,
        "Bytes": path.stat().st_size,
        "SHA-256": sha256_file(path),
        "Source URL": source_url,
        "Licence Assumption": license_name,
        "Included in Submission": included,
        "Role": role,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fnspid-shards", type=Path, nargs=2, required=True)
    parser.add_argument("--finbert-float-model", type=Path, required=True)
    parser.add_argument("--finbert-runtime-model", type=Path, required=True)
    parser.add_argument("--finbert-tokenizer", type=Path, required=True)
    parser.add_argument("--article-cache", type=Path, required=True)
    parser.add_argument("--daily-features", type=Path, required=True)
    parser.add_argument("--calendar", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    rows: list[dict[str, object]] = []
    for index, shard in enumerate(args.fnspid_shards):
        rows.append(
            record(
                category="News source",
                identifier=FNSPID_ID,
                revision=FNSPID_REVISION,
                path=shard,
                source_url=(
                    "https://huggingface.co/datasets/benstaf/"
                    "FNSPID-filtered-nasdaq-100/resolve/"
                    f"{FNSPID_REVISION}/data/train-0000{index}-of-00002.parquet"
                ),
                license_name="CC BY-NC 4.0 (conservative upstream assumption)",
                included=False,
                role="External research-only raw shard",
            )
        )
    rows.extend(
        [
            record(
                category="Text model",
                identifier=FINBERT_ID,
                revision=FINBERT_REVISION,
                path=args.finbert_float_model,
                source_url=(
                    "https://huggingface.co/ProsusAI/finbert/resolve/"
                    f"{FINBERT_REVISION}/onnx/model.onnx"
                ),
                license_name="Apache-2.0",
                included=False,
                role="Pinned upstream ONNX weights",
            ),
            record(
                category="Text runtime",
                identifier=f"{FINBERT_ID} dynamic-int8",
                revision=FINBERT_REVISION,
                path=args.finbert_runtime_model,
                source_url="Locally quantized from the pinned ONNX weights",
                license_name="Apache-2.0",
                included=False,
                role="CPU inference runtime optimisation",
            ),
            record(
                category="Tokenizer",
                identifier=FINBERT_ID,
                revision=FINBERT_REVISION,
                path=args.finbert_tokenizer,
                source_url=(
                    "https://huggingface.co/ProsusAI/finbert/resolve/"
                    f"{FINBERT_REVISION}/onnx/tokenizer.json"
                ),
                license_name="Apache-2.0",
                included=False,
                role="Pinned headline tokenizer",
            ),
            record(
                category="Derived cache",
                identifier="v7-article-finbert-cache",
                revision=FINBERT_REVISION,
                path=args.article_cache,
                source_url="Generated by scripts/score_news_finbert.py",
                license_name="Derived hashes/probabilities; no headline text",
                included=True,
                role="Article-level reproducibility evidence",
            ),
            record(
                category="Derived panel",
                identifier="v7-daily-news-features",
                revision=FNSPID_REVISION,
                path=args.daily_features,
                source_url="Generated by scripts/build_daily_news_features.py",
                license_name="Derived numeric features",
                included=True,
                role="Formal F0-F5 model input",
            ),
            record(
                category="Calendar",
                identifier="XNYS",
                revision="exchange_calendars-4.5.6",
                path=args.calendar,
                source_url="https://github.com/gerrymanoim/exchange_calendars",
                license_name="Apache-2.0",
                included=True,
                role="Strict publication-to-session mapping",
            ),
        ]
    )
    output = pd.DataFrame(rows)
    output["Manifest Generated UTC"] = datetime.now(timezone.utc).isoformat()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    output.to_csv(args.output, index=False)
    print(f"Wrote {len(output)} manifest records to {args.output}")


if __name__ == "__main__":
    main()
